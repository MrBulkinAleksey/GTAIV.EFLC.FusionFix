# Writes source/carmirrorstable.hxx: the mirror glass of every car in vehicles.img as a rectangle in the car's space
# (centre, half extents along its right and up as the driver sees it, normal towards the driver), for carmirrors.ixx.
#
#     GTAIV_EXE=bin/GTAIV.exe VEHICLES_IMG=log/vehicles.img python3 tools/vehicle_mirrors/emit.py source/carmirrorstable.hxx
import math
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from img3 import toc
from mirrors import find

INSET = 0.98  # of the glass's extent: the quad, rounded by mirror_car_shape.patch, stays inside its rim


def joaat(name):
    h = 0
    for c in name.lower().encode():
        h = (h + c) & 0xffffffff
        h = (h + (h << 10)) & 0xffffffff
        h ^= h >> 6
    h = (h + (h << 3)) & 0xffffffff
    h ^= h >> 11
    return (h + (h << 15)) & 0xffffffff


def sub(a, b): return [a[i] - b[i] for i in range(3)]
def dot(a, b): return sum(a[i] * b[i] for i in range(3))
def cross(a, b): return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]
def norm(a):
    l = math.sqrt(dot(a, a)); return [x / l for x in a]


def rectangle(pts, n):
    n = norm(list(n))
    up = norm(sub([0, 0, 1], [n[i] * n[2] for i in range(3)]))  # world up within the glass
    right = cross([-x for x in n], up)                          # as the driver, looking along -n, sees it
    o = [sum(p[i] for p in pts) / len(pts) for i in range(3)]
    rs = [dot(sub(p, o), right) for p in pts]; us = [dot(sub(p, o), up) for p in pts]
    cr = (min(rs) + max(rs)) / 2; cu = (min(us) + max(us)) / 2
    hr = (max(rs) - min(rs)) / 2 * INSET; hu = (max(us) - min(us)) / 2 * INSET
    centre = [o[i] + right[i] * cr + up[i] * cu for i in range(3)]
    return centre, [x * hr for x in right], [x * hu for x in up], n


rows = []
for e in toc(os.environ.get('VEHICLES_IMG', 'log/vehicles.img')):
    name = e[4]
    if not name.endswith('.wft'):
        continue
    try:
        found = find(name)
    except Exception:
        continue  # bikes: no glass
    for kind, side in ((0, 'L'), (1, 'R'), (2, 'C')):
        if side in found:
            c, r, u, n = rectangle(found[side][5], found[side][1])
            rows.append((joaat(name[:-4]), kind, name[:-4], c, r, u, n))

f = lambda v: ', '.join('%.4ff' % x for x in v)
out = ['// Generated by tools/vehicle_mirrors/emit.py from vehicles.img: do not edit by hand.',
       '// model hash, 0 left / 1 right / 2 interior, centre, half right, half up (as the driver sees it), normal (to him)',
       '#pragma once', '', 'struct CarMirrorGlass', '{', '    uint32_t model;', '    uint8_t kind;',
       '    float centre[3], right[3], up[3], normal[3];', '};', '',
       'inline constexpr CarMirrorGlass CarMirrorTable[] =', '{']
for h, k, nm, c, r, u, n in rows:
    out.append('    { 0x%08X, %d, { %s }, { %s }, { %s }, { %s } }, // %s' % (h, k, f(c), f(r), f(u), f(n), nm))
out.append('};')
open(sys.argv[1], 'w', newline='\n').write('\n'.join(out) + '\n')
print(len(rows), 'mirrors')
