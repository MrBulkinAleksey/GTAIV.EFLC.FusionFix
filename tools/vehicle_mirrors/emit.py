# Writes source/carmirrorstable.hxx: the mirror glass of every car in vehicles.img as a rectangle in the car's space
# (centre, half extents along its right and up as the driver sees it, normal towards the driver) and its outline in
# that rectangle (a convex polygon of up to 8 corners, -1..1), for carmirrors.ixx. The glass is the flat group find()
# picked grown over the triangles of its geometry that face within 18 degrees of it, lie within 2 cm of its plane and
# 15 cm of its middle: curved glass is more than one flat group.
#
#     GTAIV_EXE=bin/GTAIV.exe VEHICLES_IMG=log/vehicles.img python3 tools/vehicle_mirrors/emit.py source/carmirrorstable.hxx
import math
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from img3 import toc
from mirrors import find, tris
from wft import parse

OUTLINE = 8  # corners of the outline at most, as mirror_car_shape.patch tests them


def joaat(name):
    h = 0
    for c in name.lower().encode():
        h = (h + c) & 0xffffffff
        h = (h + (h << 10)) & 0xffffffff
        h ^= h >> 6
    h = (h + (h << 3)) & 0xffffffff
    h ^= h >> 11
    return (h + (h << 15)) & 0xffffffff


def sub(a, b): return [a[i] - b[i] for i in range(3)]
def dot(a, b): return sum(a[i] * b[i] for i in range(3))
def cross(a, b): return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]
def norm(a):
    l = math.sqrt(dot(a, a)); return [x / l for x in a]


def grow(geometry, pts, n):
    n = norm(list(n))
    o = [sum(p[i] for p in pts) / len(pts) for i in range(3)]
    d0 = dot(n, o)
    grown = list(pts)
    for tn, (a, b, c), area in tris(geometry):
        if dot(tn, n) < 0.95:
            continue
        m = [(a[i] + b[i] + c[i]) / 3 for i in range(3)]
        if abs(dot(n, m) - d0) > 0.02 or math.sqrt(dot(sub(m, o), sub(m, o))) > 0.15:
            continue
        grown += [a, b, c]
    return grown


def hull(points):
    points = sorted(set(points))
    if len(points) < 3:
        return points
    def turn(o, a, b): return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])
    lower, upper = [], []
    for p in points:
        while len(lower) >= 2 and turn(lower[-2], lower[-1], p) <= 0: lower.pop()
        lower.append(p)
    for p in reversed(points):
        while len(upper) >= 2 and turn(upper[-2], upper[-1], p) <= 0: upper.pop()
        upper.append(p)
    return lower[:-1] + upper[:-1]  # counter-clockwise


def simplify(polygon, most):
    polygon = list(polygon)
    while len(polygon) > most:  # drop the corner whose triangle with its neighbours is the smallest
        def area(i):
            a, b, c = polygon[i - 1], polygon[i], polygon[(i + 1) % len(polygon)]
            return abs((b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0]))
        del polygon[min(range(len(polygon)), key=area)]
    return polygon


def rectangle(pts, n):
    n = norm(list(n))
    up = norm(sub([0, 0, 1], [n[i] * n[2] for i in range(3)]))  # world up within the glass
    right = cross([-x for x in n], up)                          # as the driver, looking along -n, sees it
    o = [sum(p[i] for p in pts) / len(pts) for i in range(3)]
    rs = [dot(sub(p, o), right) for p in pts]; us = [dot(sub(p, o), up) for p in pts]
    cr = (min(rs) + max(rs)) / 2; cu = (min(us) + max(us)) / 2
    hr = (max(rs) - min(rs)) / 2; hu = (max(us) - min(us)) / 2
    centre = [o[i] + right[i] * cr + up[i] * cu for i in range(3)]
    flat = [(round((r - cr) / hr, 4), round((u - cu) / hu, 4)) for r, u in zip(rs, us)]
    outline = simplify(hull(flat), OUTLINE)
    return centre, [x * hr for x in right], [x * hu for x in up], n, outline


rows = []
for e in toc(os.environ.get('VEHICLES_IMG', 'log/vehicles.img')):
    name = e[4]
    if not name.endswith('.wft'):
        continue
    try:
        found = find(name)
    except Exception:
        continue  # bikes: no glass
    geometries = parse(name)[1]
    for kind, side in ((0, 'L'), (1, 'R'), (2, 'C')):
        if side in found:
            area, n, box, gi, shader, pts = found[side]
            c, r, u, n, outline = rectangle(grow(geometries[gi], pts, n), n)
            rows.append((joaat(name[:-4]), kind, name[:-4], c, r, u, n, outline))

f = lambda v: ', '.join('%.4ff' % x for x in v)
out = ['// Generated by tools/vehicle_mirrors/emit.py from vehicles.img: do not edit by hand.',
       '// model hash, 0 left / 1 right / 2 interior, centre, half right, half up (as the driver sees it), normal (to him),',
       '// the outline\'s corners (counter-clockwise in right, up; -1..1) and how many',
       '#pragma once', '', 'struct CarMirrorGlass', '{', '    uint32_t model;', '    uint8_t kind;',
       '    float centre[3], right[3], up[3], normal[3];', '    float outline[%d][2];' % OUTLINE, '    uint8_t corners;', '};', '',
       'inline constexpr CarMirrorGlass CarMirrorTable[] =', '{']
for h, k, nm, c, r, u, n, outline in rows:
    corners = ', '.join('{ %.3ff, %.3ff }' % p for p in outline)
    out.append('    { 0x%08X, %d, { %s }, { %s }, { %s }, { %s }, { %s }, %d }, // %s' % (h, k, f(c), f(r), f(u), f(n), corners, len(outline), nm))
out.append('};')
open(sys.argv[1], 'w', newline='\n').write('\n'.join(out) + '\n')
print(len(rows), 'mirrors')
